-- Schema Bridge export for MySQL 8 / MariaDB 10.3+.
-- Read-only: it only reads information_schema, never table contents.
-- Run it while the database you want to export is selected (USE your_database;).
SELECT 'column' AS record_type, c.TABLE_SCHEMA AS table_schema, c.TABLE_NAME AS table_name,
       CASE t.TABLE_TYPE WHEN 'VIEW' THEN 'view' ELSE 'table' END AS object_type,
       c.ORDINAL_POSITION AS ordinal_position, c.COLUMN_NAME AS column_name, c.COLUMN_TYPE AS data_type,
       c.IS_NULLABLE AS is_nullable,
       CASE WHEN c.EXTRA LIKE '%auto_increment%' THEN 'auto_increment' ELSE c.COLUMN_DEFAULT END AS column_default,
       CASE WHEN t.TABLE_TYPE = 'VIEW' THEN NULL ELSE NULLIF(t.TABLE_COMMENT, '') END AS table_comment,
       NULLIF(c.COLUMN_COMMENT, '') AS column_comment,
       NULL AS constraint_name, NULL AS constraint_type, NULL AS definition, NULL AS ref_schema, NULL AS ref_table,
       NULL AS indexname, NULL AS indexdef, NULL AS estimated_rows, NULL AS triggers, 'mysql' AS dbms
FROM information_schema.COLUMNS c
JOIN information_schema.TABLES t ON t.TABLE_SCHEMA = c.TABLE_SCHEMA AND t.TABLE_NAME = c.TABLE_NAME
WHERE c.TABLE_SCHEMA = DATABASE()
UNION ALL
SELECT 'constraint', tc.TABLE_SCHEMA, tc.TABLE_NAME, NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL,
       CASE WHEN tc.CONSTRAINT_TYPE = 'PRIMARY KEY' THEN CONCAT(tc.TABLE_NAME, '_pkey') ELSE tc.CONSTRAINT_NAME END,
       tc.CONSTRAINT_TYPE,
       CONCAT(tc.CONSTRAINT_TYPE, ' (', GROUP_CONCAT(k.COLUMN_NAME ORDER BY k.ORDINAL_POSITION SEPARATOR ', '), ')'),
       NULL, NULL, NULL, NULL, NULL, NULL, 'mysql'
FROM information_schema.TABLE_CONSTRAINTS tc
JOIN information_schema.KEY_COLUMN_USAGE k
  ON k.CONSTRAINT_SCHEMA = tc.CONSTRAINT_SCHEMA AND k.CONSTRAINT_NAME = tc.CONSTRAINT_NAME AND k.TABLE_NAME = tc.TABLE_NAME
WHERE tc.TABLE_SCHEMA = DATABASE() AND tc.CONSTRAINT_TYPE IN ('PRIMARY KEY', 'UNIQUE')
GROUP BY tc.TABLE_SCHEMA, tc.TABLE_NAME, tc.CONSTRAINT_NAME, tc.CONSTRAINT_TYPE
UNION ALL
SELECT 'constraint', k.TABLE_SCHEMA, k.TABLE_NAME, NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL,
       k.CONSTRAINT_NAME, 'FOREIGN KEY',
       CONCAT('FOREIGN KEY (', GROUP_CONCAT(k.COLUMN_NAME ORDER BY k.ORDINAL_POSITION SEPARATOR ', '),
              ') REFERENCES ', k.REFERENCED_TABLE_NAME, '(',
              GROUP_CONCAT(k.REFERENCED_COLUMN_NAME ORDER BY k.ORDINAL_POSITION SEPARATOR ', '), ')',
              CASE WHEN r.DELETE_RULE IN ('CASCADE', 'SET NULL', 'SET DEFAULT') THEN CONCAT(' ON DELETE ', r.DELETE_RULE) ELSE '' END),
       k.REFERENCED_TABLE_SCHEMA, k.REFERENCED_TABLE_NAME, NULL, NULL, NULL, NULL, 'mysql'
FROM information_schema.KEY_COLUMN_USAGE k
JOIN information_schema.REFERENTIAL_CONSTRAINTS r
  ON r.CONSTRAINT_SCHEMA = k.CONSTRAINT_SCHEMA AND r.CONSTRAINT_NAME = k.CONSTRAINT_NAME AND r.TABLE_NAME = k.TABLE_NAME
WHERE k.TABLE_SCHEMA = DATABASE() AND k.REFERENCED_TABLE_NAME IS NOT NULL
GROUP BY k.TABLE_SCHEMA, k.TABLE_NAME, k.CONSTRAINT_NAME, k.REFERENCED_TABLE_SCHEMA, k.REFERENCED_TABLE_NAME, r.DELETE_RULE
UNION ALL
SELECT 'index', s.TABLE_SCHEMA, s.TABLE_NAME, NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL,
       NULL, NULL, NULL, NULL, NULL, s.INDEX_NAME,
       CONCAT('CREATE ', CASE WHEN s.NON_UNIQUE = 0 THEN 'UNIQUE ' ELSE '' END, 'INDEX ', s.INDEX_NAME, ' ON ', s.TABLE_NAME,
              ' (', GROUP_CONCAT(s.COLUMN_NAME ORDER BY s.SEQ_IN_INDEX SEPARATOR ', '), ')'),
       NULL, NULL, 'mysql'
FROM information_schema.STATISTICS s
WHERE s.TABLE_SCHEMA = DATABASE()
GROUP BY s.TABLE_SCHEMA, s.TABLE_NAME, s.INDEX_NAME, s.NON_UNIQUE
UNION ALL
SELECT 'table', t.TABLE_SCHEMA, t.TABLE_NAME, NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL,
       NULL, NULL, NULL, NULL, NULL, NULL, NULL, t.TABLE_ROWS,
       (SELECT GROUP_CONCAT(tr.TRIGGER_NAME SEPARATOR ', ') FROM information_schema.TRIGGERS tr
         WHERE tr.EVENT_OBJECT_SCHEMA = t.TABLE_SCHEMA AND tr.EVENT_OBJECT_TABLE = t.TABLE_NAME),
       'mysql'
FROM information_schema.TABLES t
WHERE t.TABLE_SCHEMA = DATABASE() AND t.TABLE_TYPE = 'BASE TABLE'
ORDER BY 1, 2, 3;
